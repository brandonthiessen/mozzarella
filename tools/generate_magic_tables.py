#!/usr/bin/env python3
"""Generate validated C++ magic-bitboard lookup tables from magic-search CSVs.

Usage:
  python3 tools/generate_magic_tables.py BISHOP.csv ROOK.csv src/magics_data.inc

CSV files must be the outputs of tools/magic_search.cpp and contain one row per square.
This script independently regenerates relevant masks and ray attacks, validates every
magic over every relevant occupancy subset, then emits constants and contiguous tables.
"""

import csv
import sys
from pathlib import Path

MASK64 = (1 << 64) - 1
ROOK_DIRS = ((1, 0), (-1, 0), (0, 1), (0, -1))
BISHOP_DIRS = ((1, 1), (1, -1), (-1, 1), (-1, -1))


def relevant_mask(square: int, bishop: bool) -> int:
    dirs = BISHOP_DIRS if bishop else ROOK_DIRS
    rank, file = divmod(square, 8)
    mask = 0
    for dr, df in dirs:
        r, f = rank + dr, file + df
        while 0 <= r < 8 and 0 <= f < 8:
            nr, nf = r + dr, f + df
            # Exclude the final square on each ray: edge blockers cannot change attacks.
            if not (0 <= nr < 8 and 0 <= nf < 8):
                break
            mask |= 1 << (r * 8 + f)
            r, f = nr, nf
    return mask


def ray_attacks(square: int, occupancy: int, bishop: bool) -> int:
    dirs = BISHOP_DIRS if bishop else ROOK_DIRS
    rank, file = divmod(square, 8)
    attacks = 0
    for dr, df in dirs:
        r, f = rank + dr, file + df
        while 0 <= r < 8 and 0 <= f < 8:
            bit = 1 << (r * 8 + f)
            attacks |= bit
            if occupancy & bit:
                break
            r += dr
            f += df
    return attacks


def read_csv(path: Path, bishop: bool):
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    by_square = {}
    for row in rows:
        try:
            sq = int(row["square"])
            magic = int(row["magic"], 0)
            bits = int(row["index_bits"])
            shift = int(row["shift"])
            entries = int(row["table_entries"])
        except (KeyError, TypeError, ValueError) as e:
            raise ValueError(f"{path}: malformed CSV row {row!r}: {e}") from e
        if not 0 <= sq < 64:
            raise ValueError(f"{path}: invalid square {sq}")
        if sq in by_square:
            raise ValueError(f"{path}: duplicate row for square {sq}")
        if not 1 <= bits <= 20 or shift != 64 - bits or entries != (1 << bits):
            raise ValueError(f"{path}: inconsistent bits/shift/table_entries for square {sq}")
        mask = relevant_mask(sq, bishop)
        # A magic may use fewer index bits than mask popcount, but not more.
        if bits > mask.bit_count():
            raise ValueError(f"{path}: square {sq} uses {bits} index bits for a {mask.bit_count()}-bit mask")
        by_square[sq] = (magic, bits, shift, entries, mask)
    missing = sorted(set(range(64)) - by_square.keys())
    if missing:
        raise ValueError(f"{path}: missing squares {missing}")

    magics, shifts, masks, offsets, table = [], [], [], [], []
    for sq in range(64):
        magic, bits, shift, entries, mask = by_square[sq]
        local = [0] * entries
        filled = [False] * entries
        subset = mask
        while True:
            idx = (((subset * magic) & MASK64) >> shift)
            if idx >= entries:
                raise ValueError(f"{path}: square {sq} produced out-of-range index {idx}")
            attack = ray_attacks(sq, subset, bishop)
            if filled[idx] and local[idx] != attack:
                raise ValueError(
                    f"{path}: INVALID magic at square {sq}: destructive collision at index {idx}"
                )
            local[idx] = attack
            filled[idx] = True
            if subset == 0:
                break
            subset = (subset - 1) & mask
        # Unused slots can occur with constructive-collision magics; zero is safe because
        # no occupancy can index an unused slot. Keep all slots for direct indexing.
        offsets.append(len(table))
        table.extend(local)
        magics.append(magic)
        shifts.append(shift)
        masks.append(mask)

    expected = sum(by_square[sq][3] for sq in range(64))
    if len(table) != expected:
        raise AssertionError("internal table-size mismatch")
    return magics, shifts, masks, offsets, table


def fmt_array(ctype, name, values, per_line=4, formatter=str):
    out = [f"inline constexpr std::array<{ctype}, {len(values)}> {name} = {{{{"]
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(formatter(v) for v in values[i:i + per_line]) + ",")
    out.append("}};")
    return "\n".join(out)


def emit(path: Path, bishop_data, rook_data):
    parts = [
        "// Generated by tools/generate_magic_tables.py. Do not edit by hand.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "namespace mozzarella {",
    ]
    for label, data in (("BISHOP", bishop_data), ("ROOK", rook_data)):
        magics, shifts, masks, offsets, table = data
        parts.append(fmt_array("std::uint64_t", f"GENERATED_{label}_MAGICS", magics, 2, lambda x: f"0x{x:016x}ULL"))
        parts.append(fmt_array("std::uint8_t", f"GENERATED_{label}_SHIFTS", shifts, 8))
        parts.append(fmt_array("std::uint64_t", f"GENERATED_{label}_RELEVANCY_MASKS", masks, 2, lambda x: f"0x{x:016x}ULL"))
        parts.append(fmt_array("std::uint32_t", f"GENERATED_{label}_OFFSETS", offsets, 8))
        parts.append(fmt_array("std::uint64_t", f"GENERATED_{label}_ATTACKS", table, 4, lambda x: f"0x{x:016x}ULL"))
    parts.append("} // namespace mozzarella")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(parts) + "\n", encoding="utf-8")


def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} BISHOP.csv ROOK.csv OUTPUT.inc", file=sys.stderr)
        return 2
    bishop_csv, rook_csv, output = map(Path, sys.argv[1:])
    try:
        bishop = read_csv(bishop_csv, True)
        rook = read_csv(rook_csv, False)
        emit(Path(output), bishop, rook)
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"Validated 64 bishop and 64 rook magics.")
    print(f"Bishop entries: {len(bishop[4])}; rook entries: {len(rook[4])}; total: {len(bishop[4]) + len(rook[4])}.")
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
